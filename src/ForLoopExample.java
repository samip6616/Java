/*The for loop
Use a for loop when you know how many times you want to repeat something.
Syntax
for (initialization; condition; update) {
    // Code to repeat
}

- Initialization: Sets the starting value.
- Condition: Determines whether the loop continues.
- Update: Changes the value after each iteration.
Example: */
public class ForLoopExample {
    public static void main(String[] args) {
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }
    }
}